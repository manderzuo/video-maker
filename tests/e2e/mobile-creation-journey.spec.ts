test('waits for video input composition before saving the graph', async ({ page, workspace }) => {
    const h = workspace.headers(workspace.account), project = (await workspace.call('POST', '/studio-api/projects', { ...h, payload: { title: 'TEST DATA 视频合成输入' } })).json();
    workspace.setVideoSpecs([{ modelId: 'seedance', durationSeconds: 5, ratio: '9:16', resolution: '480p' }]);
    await workspace.call('PATCH', '/studio-api/me/model-configs/video', { ...h, payload: { apiBase: 'https://video.example.test', model: 'seedance', apiKey: 'FAKE_MOBILE_KEY', expectedRevision: null } });
    await page.clock.install();
    await page.goto('/m/projects/' + project.id + '/video');
    await page.getByRole('button', { name: '新建视频草稿', exact: true }).click();
    const input = page.locator('[data-interaction-id="cloud:video:new-text"]');
    await input.focus();
    await input.dispatchEvent('compositionstart');
    await input.fill('TEST DATA 中文正在输入');
    await page.clock.fastForward(4000);
    expect((await workspace.call('GET', '/studio-api/projects/' + project.id + '/graph', h)).json().revision).toBe(0);
    await expect(input).toBeFocused();
    await input.dispatchEvent('compositionend');
    await page.clock.fastForward(4000);
    await expect.poll(async () => (await workspace.call('GET', '/studio-api/projects/' + project.id + '/graph', h)).json().revision).toBe(1);
    await expect(input).toHaveValue('TEST DATA 中文正在输入');
});
test('can explicitly discard a conflicting mobile video edit and reload the desktop revision', async ({ page, workspace }) => {
    const h = workspace.headers(workspace.account), project = (await workspace.call('POST', '/studio-api/projects', { ...h, payload: { title: 'TEST DATA 视频冲突' } })).json();
    workspace.setVideoSpecs(['480p', '720p'].map(resolution => ({ modelId: 'seedance', durationSeconds: 5, ratio: '9:16', resolution })));
    await workspace.call('PATCH', '/studio-api/me/model-configs/video', { ...h, payload: { apiBase: 'https://video.example.test', model: 'seedance', apiKey: 'FAKE_MOBILE_KEY', expectedRevision: null } });
    await page.goto('/m/projects/' + project.id + '/video');
    await page.getByRole('button', { name: '新建视频草稿', exact: true }).click();
    await expect(page.getByText('视频草稿已保存', { exact: true })).toBeVisible();
    const graph = (await workspace.call('GET', '/studio-api/projects/' + project.id + '/graph', h)).json();
    await workspace.call('POST', '/studio-api/projects/' + project.id + '/commands', { ...h, payload: { expectedRevision: graph.revision, idempotencyKey: randomUUID(), command: { type: 'operations', operations: [{ id: randomUUID(), type: 'update_node', payload: { nodeId: graph.nodes[0].id, patch: { title: 'TEST DATA 电脑端已修改' } } }] } } });
    await page.getByLabel('视频清晰度', { exact: true }).selectOption('720p');
    await expect(page.getByText('保存未完成，输入保留，请重试', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '放弃本页修改并重新读取', exact: true }).click();
    const discard = page.getByRole('dialog', { name: '放弃视频草稿修改', exact: true });
    await discard.getByRole('button', { name: '确认放弃并重新读取', exact: true }).click();
    await expect(page.getByText('视频草稿已保存', { exact: true })).toBeVisible();
    await expect(page.getByLabel('选择视频草稿', { exact: true })).toContainText('TEST DATA 电脑端已修改');
    await expect(page.getByLabel('视频清晰度', { exact: true })).toHaveValue('480p');
    expect(workspace.providerCalls.filter(call => call.method === 'POST')).toHaveLength(0);
});
