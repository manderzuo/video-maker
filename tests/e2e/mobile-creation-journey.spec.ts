test('creates, polishes, revises and continues a mobile video with one confirmed submission', async ({ page, workspace, browserName }, testInfo) => {
    const h = workspace.headers(workspace.account), project = (await workspace.call('POST', '/studio-api/projects', { ...h, payload: { title: 'TEST DATA 手机创作' } })).json();
    workspace.setVideoReferenceSupport({ imageReferences: 1, videoReferences: 0, assetUploads: true });
    workspace.setVideoSpecs(['480p', '720p'].map(resolution => ({ modelId: 'seedance', durationSeconds: 5, ratio: '9:16', resolution })));
    await workspace.call('PATCH', '/studio-api/me/model-configs/video', { ...h, payload: { apiBase: 'https://video.example.test', model: 'seedance', apiKey: 'FAKE_MOBILE_KEY', expectedRevision: null } });
    await workspace.call('PATCH', '/studio-api/me/model-configs/text', { ...h, payload: { apiBase: 'https://api.example.test', model: 'Vendor/Cloud-Text', apiKey: 'FAKE_TEXT_UI_KEY', expectedRevision: null } });
    await page.goto('/m/projects/' + project.id + '/video');
    await expect(page.getByRole('heading', { name: '视频创作', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '新建视频草稿', exact: true }).click();
    await page.locator('[data-interaction-id="cloud:video:new-text"]').fill('雨后的街道，5秒，9:16竖屏，一镜到底');
    await page.getByRole('button', { name: '保存文字并连接', exact: true }).click();
    await page.getByLabel('视频清晰度', { exact: true }).selectOption('720p');
    await expect(page.getByText('视频草稿已保存', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '生成视频', exact: true }).click();
    const confirm = page.getByRole('dialog', { name: '确认云端视频生成', exact: true });
    await expect(confirm).toBeVisible();
    await expect(confirm).toHaveClass(/mobile-dialog/);
    await expect(confirm).toContainText('720p');
    await confirm.getByRole('button', { name: '确认', exact: true }).click({ clickCount: 2 });
    await expect(confirm).not.toBeVisible();
    await expect.poll(async () => Number((await workspace.pool.query('SELECT COUNT(*)::int n FROM workspace_video_runs')).rows[0].n)).toBe(1);
    await expect.poll(async () => (await workspace.pool.query("SELECT document->>'executionState' state FROM workspace_video_runs")).rows[0]?.state, { timeout: 15000 }).toBe('succeeded');
    await page.getByRole('link', { name: '查看视频结果', exact: true }).click();
    await expect(page).toHaveURL(new RegExp('/m/projects/' + project.id + '/results'));
    await page.getByRole('button', { name: '修改后重新生成', exact: true }).click();
    const revision = page.getByRole('dialog', { name: '修改后重新生成', exact: true });
    await expect(revision.locator('[data-interaction-id="cloud:results:revision-text-settings"]')).toHaveAttribute('href', '/m/settings/connections#text-api');
    await revision.locator('[data-interaction-id="cloud:results:revision-prompt"]').fill('改成日落街道，保持原镜头');
    await revision.getByLabel('需要修正的问题', { exact: true }).fill('修复车轮变形，保持镜头');
    await revision.getByRole('button', { name: '文字 API 润色', exact: true }).click();
    const polish = page.getByRole('dialog', { name: '确认 AI 文字优化', exact: true });
    await expect(polish).toHaveClass(/mobile-dialog/);
    await polish.getByLabel('我确认此文字调用可能收费', { exact: true }).check();
    await polish.getByRole('button', { name: '确认调用文字模型', exact: true }).click();
    const panel = page.locator('.prompt-generator-panel');
    await panel.getByRole('tab', { name: '结果', exact: true }).click();
    await expect(panel.getByLabel('结果正文', { exact: true })).toHaveValue('云端 AI 优化的雨后街道');
    await panel.getByRole('button', { name: '采用润色正文', exact: true }).click();
    await expect(revision.locator('[data-interaction-id="cloud:results:revision-prompt"]')).toHaveValue('云端 AI 优化的雨后街道');
    await revision.getByRole('button', { name: '保存为新的视频草稿', exact: true }).click();
    await expect(page).toHaveURL(new RegExp('/m/projects/' + project.id + '/video\\?node='));
    const graph = (await workspace.call('GET', '/studio-api/projects/' + project.id + '/graph', h)).json();
    expect(graph.nodes.filter((node: {
        type: string;
    }) => node.type === 'video-generation')).toHaveLength(2);
    expect(graph.nodes.filter((node: {
        type: string;
    }) => node.type === 'result')).toHaveLength(1);
    expect(workspace.providerCalls.filter(call => call.method === 'POST' && call.url.includes('/videos/'))).toHaveLength(1);
    expect(workspace.providerCalls.filter(call => call.method === 'POST' && call.url.includes('/chat/'))).toHaveLength(1);
    await page.goto('/m/projects/' + project.id + '/results');
    await page.getByRole('button', { name: '尾帧续写', exact: true }).click();
    const tail = page.getByRole('dialog', { name: '尾帧续写', exact: true });
    const decoded = browserName !== 'webkit' || await page.evaluate(url => new Promise<boolean>(resolve => { const video = document.createElement('video'); video.muted = true; video.preload = 'auto'; const finish = (ok: boolean) => { clearTimeout(timer); video.removeAttribute('src'); video.load(); video.remove(); resolve(ok); }, timer = setTimeout(() => finish(false), 5000); video.onloadeddata = () => finish(true); video.onerror = () => finish(false); document.body.append(video); video.src = url; }), 'data:video/mp4;base64,' + readFileSync(new URL('../fixtures/cloud-result-clip.mp4', import.meta.url)).toString('base64'));
    if (!decoded) {
        testInfo.annotations.push({ type: 'studio:media-limitation', description: 'Engine lacks H.264: generation/revision verified; tail-frame decode and playback await real-device acceptance' });
        await expect(tail.getByRole('alert')).toContainText('无法读取该视频');
        expect(workspace.providerCalls.filter(call => call.method === 'POST' && call.url.includes('/videos/'))).toHaveLength(1);
        return;
    }
    await expect(tail.getByAltText('尾帧预览')).toBeVisible();
    await tail.locator('[data-interaction-id="cloud:results:tail-frame-prompt"]').fill('从尾帧继续推进');
    await tail.getByRole('button', { name: '上传尾帧并保存续写流程', exact: true }).click();
    await expect(tail).not.toBeVisible();
    await expect(page).toHaveURL(new RegExp('/m/projects/' + project.id + '/video'));
    const continued = (await workspace.call('GET', '/studio-api/projects/' + project.id + '/graph', h)).json();
    expect(continued.nodes.filter((node: {
        type: string;
    }) => node.type === 'video-generation')).toHaveLength(3);
    expect(workspace.providerCalls.filter(call => call.method === 'POST' && call.url.includes('/videos/'))).toHaveLength(1);
});
