    await page.getByRole('tab', { name: '结果', exact: true }).click();
    await page.getByRole('button', { name: '插入文字', exact: true }).first().click();
    await apply.locator('[data-interaction-id="cloud:draft:apply-mode-flow"]').check();
    await apply.getByLabel('目标项目', { exact: true }).selectOption(project.id);
    await apply.getByLabel('执行规格', { exact: true }).selectOption({ index: 1 });
    await apply.getByRole('button', { name: '确认应用到云端画布', exact: true }).click();
