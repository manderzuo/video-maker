import { randomUUID } from 'node:crypto';
import { test, expect } from '../helpers/cloud-workspace-ui-fixture';
import type { Page, TestType } from '@playwright/test';
type FixtureArgs<T> = T extends TestType<infer Args, infer Worker> ? Args & Worker : never;
type Workspace = FixtureArgs<typeof test>['workspace'];
async function videoProject(page: Page, workspace: Workspace) {
    const h = workspace.headers(workspace.account), project = (await workspace.call('POST', '/studio-api/projects', { ...h, payload: { title: 'TEST DATA 手机审查' } })).json();
    workspace.setVideoSpecs([{ modelId: 'seedance', durationSeconds: 5, ratio: '9:16', resolution: '480p' }]);
    await workspace.call('PATCH', '/studio-api/me/model-configs/video', { ...h, payload: { apiBase: 'https://video.example.test', model: 'seedance', apiKey: 'FAKE_MOBILE_KEY', expectedRevision: null } });
    await page.goto('/m/projects/' + project.id + '/video');
    await page.getByRole('button', { name: '新建视频草稿', exact: true }).click();
    return project;
}
test('keeps ordinary mobile video typing enabled during a slow automatic graph save', async ({ page, context, workspace }) => {
    await page.clock.install();
    let release!: () => void;
    const gate = new Promise<void>(resolve => { release = resolve; });
    await context.route('**/studio-api/projects/*/commands', async route => { await gate; await route.fallback(); });
    try {
        await videoProject(page, workspace);
        const input = page.locator('[data-interaction-id="cloud:video:new-text"]');
        await input.fill('TEST DATA 正常打字');
        await page.clock.fastForward(2500);
        await expect(page.getByText('正在保存视频草稿…', { exact: true })).toBeVisible();
        await expect(input).toBeEnabled();
        await expect(input).toBeFocused();
        await input.press('End');
        await input.pressSequentially(' more');
        await expect(input).toHaveValue('TEST DATA 正常打字 more');
    } finally { release(); }
    await expect(page.getByText('视频草稿已保存', { exact: true })).toBeVisible();
});
test('retains mobile input through a transient session failure and erases it on account change', async ({ page, context, workspace }) => {
    const project = await videoProject(page, workspace);
    await expect(page.getByText('视频草稿已保存', { exact: true })).toBeVisible();
    const input = page.locator('[data-interaction-id="cloud:video:new-text"]');
    await input.fill('TEST DATA 弱网中保留正文');
    let offline = true;
    await context.route('**/studio-api/session', route => offline ? route.abort('failed') : route.fallback());
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    const retry = page.getByRole('button', { name: '重新检查登录', exact: true });
    await expect(retry).toBeVisible();
    await expect(input).toHaveValue('TEST DATA 弱网中保留正文');
    await expect(input).not.toBeVisible();
    offline = false;
    await retry.click();
    await expect(input).toBeVisible();
    await expect(input).toHaveValue('TEST DATA 弱网中保留正文');
    await page.getByRole('button', { name: '保存文字并连接', exact: true }).click();
    await expect(page.getByText('视频草稿已保存', { exact: true })).toBeVisible();
    expect((await workspace.call('GET', '/studio-api/projects/' + project.id + '/graph', workspace.headers(workspace.account))).json().nodes.some((n: { data: { text?: string } }) => n.data.text === 'TEST DATA 弱网中保留正文')).toBe(true);
    await page.getByRole('button', { name: '新建视频草稿', exact: true }).click();
    await expect(page.getByText('视频草稿已保存', { exact: true })).toBeVisible();
    await input.fill('TEST DATA 只属于旧账号');
    workspace.switchAccount(await workspace.signup('Cloud_UI_B'));
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await expect(page.locator('.mobile-header')).toContainText('Cloud_UI_B');
    await expect(input).toHaveCount(0);
    await page.getByRole('link', { name: '任务', exact: true }).click();
    await expect(page).toHaveURL(/\/m\/tasks$/);
});
